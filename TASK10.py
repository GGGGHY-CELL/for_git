# Запрашиваем команду у пользователя
# Метод .lower() переводит текст в нижний регистр, чтобы "СТАРТ" или "Старт" тоже работали
команда = input("Введите команду (старт, стоп, пауза): ").strip().lower()

# Обрабатываем команду с помощью match-case
match команда:
    case "старт":
        print("Запуск процесса...")
    case "стоп":
        print("Остановка процесса.")
    case "пауза":
        print("Процесс приостановлен.")
    case _:
        # Этот блок сработает для любой другой строки
        print("неизвестная команда")
