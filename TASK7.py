# Пример кортежа с координатами (x, y)
# Вы можете менять эти значения для проверки разных ситуаций
точка = (0, 5)

# Используем match-case для анализа структуры и значений кортежа
match точка:
    case (0, 0):
        print("Точка находится в начале координат.")
    case (x, 0):
        print(f"Точка лежит на оси X (координата x = {x}).")
    case (0, y):
        print(f"Точка лежит на оси Y (координата y = {y}).")
    case (x, y):
        print(f"Это обычная точка на плоскости с координатами ({x}, {y}).")
    case _:
        print("Ошибка: передан некорректный формат данных (ожидался кортеж из двух чисел).")
