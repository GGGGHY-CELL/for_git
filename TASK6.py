# Запрашиваем номер дня недели у пользователя
номер_дня = int(input("Введите число от 1 до 7: "))

# Используем конструкцию match-case для выбора правильного дня
match номер_дня:
    case 1:
        print("Понедельник")
    case 2:
        print("Вторник")
    case 3:
        print("Среда")
    case 4:
        print("Четверг")
    case 5:
        print("Пятница")
    case 6:
        print("Суббота")
    case 7:
        print("Воскресенье")
    case _:
        # Символ подчёркивания (_) срабатывает, если ни один из вариантов выше не подошёл
        print("Ошибка: введено неверное число! Пожалуйста, введите число от 1 до 7.")
