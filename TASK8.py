список_данных = ["Кот", "Собака"]
match список_данных:
    case []:
        print("пусто")
    case [единственный_элемент]:
        print(f"Один элемент: {единственный_элемент}")
    case [первый, второй]:
        print(f"Два элемента: {первый} и {второй}")
    case _:
        print("много элементов")